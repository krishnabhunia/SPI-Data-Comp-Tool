        private static readonly Color OldMuted = Color.FromArgb(90, 90, 90), OldText = Color.FromArgb(26, 26, 26);

        private static bool IsOneOf(Color asked, params Color[] known)
        {
            foreach (Color k in known) if (k.ToArgb() == asked.ToArgb()) return true;
            return false;
        }

        /// <summary>
        /// The readable colour, in the current theme, for a colour a window asks for by meaning:
        /// black for ordinary text, red for an error, green for success, blue for information.
        /// Red on a dark window, or dark blue on it, would be unreadable; other colours are kept.
        /// </summary>
        public static Color Readable(Color asked)
        {
            return Readable(asked, Current);
        }

        private static Color Readable(Color asked, UiPalette p)
        {
            if (asked.IsEmpty) return p.TextColor;
            if (IsOneOf(asked, Color.Black, SystemColors.ControlText, SystemColors.WindowText, OldText)) return p.TextColor;
            if (IsOneOf(asked, OldMuted, Color.Gray, Color.DimGray)) return p.MutedText;
            if (IsOneOf(asked, Color.Red, Color.DarkRed, Color.Firebrick, Color.Maroon, Color.Crimson)) return p.Danger;
            if (IsOneOf(asked, Color.Green, Color.DarkGreen, Color.ForestGreen, Color.SeaGreen)) return p.Success;
            if (IsOneOf(asked, Color.Blue, Color.DarkBlue, Color.Navy, Color.MediumBlue, Color.BlueViolet, Color.RoyalBlue)) return p.Info;
            foreach (UiPalette other in All)
            {
                // a colour taken from a theme earlier follows the theme
                if (other.TextColor.ToArgb() == asked.ToArgb()) return p.TextColor;
                if (other.MutedText.ToArgb() == asked.ToArgb()) return p.MutedText;
                if (other.Danger.ToArgb() == asked.ToArgb()) return p.Danger;
                if (other.Success.ToArgb() == asked.ToArgb()) return p.Success;
                if (other.Info.ToArgb() == asked.ToArgb()) return p.Info;
            }
            return asked;
        }

        private static bool SetsOwnColor(Label label)
        {
            Color inherited = label.Parent != null ? label.Parent.ForeColor : Control.DefaultForeColor;
            return label.ForeColor.ToArgb() != inherited.ToArgb();
        }

        private static void StyleLabel(Label label, Look look, UiPalette p, int zone)
        {
            if (!look.Hooked) label.ForeColorChanged += OnLabelColorChanged;
            if (!look.HasTone && SetsOwnColor(label))
            {
                look.HasTone = true;
                look.Tone = label.ForeColor;
            }
            Tone(label, look, p, zone);
        }

        private static void Tone(Label label, Look look, UiPalette p, int zone)
        {
            Color wanted;
            if (zone == ZoneHeader) wanted = p.HeadText;
            else if (zone == ZoneStatus)
            {
                // ordinary and muted text use the bar's own colour; an error stays an error
                wanted = look.HasTone ? Readable(look.Tone, p) : p.StatusText;
                if (wanted.ToArgb() == p.TextColor.ToArgb() || wanted.ToArgb() == p.MutedText.ToArgb()) wanted = p.StatusText;
            }
            else if (look.HasTone) wanted = Readable(look.Tone, p);
            else return;
            if (label.ForeColor.ToArgb() == wanted.ToArgb()) return;
            look.Toning = true;
            try { label.ForeColor = wanted; }
            finally { look.Toning = false; }
        }

        private static void OnLabelColorChanged(object sender, EventArgs e)
        {
            var label = (Label)sender;
            Look look = Of(label);
            if (look.Toning) return;
            if (!SetsOwnColor(label))
            {
                // back to the window's ordinary text colour: an earlier "error" colour must not return on the next theme change
                look.HasTone = false;
                return;
            }
            look.HasTone = true;
            look.Tone = label.ForeColor;
            Tone(label, look, Current, ZoneOf(label));
        }

        private static void StyleText(TextBoxBase box, Look look, UiPalette p, bool darknessChanged)
        {
            var text = box as TextBox;
            if (text != null) text.BorderStyle = BorderStyle.FixedSingle;
            var rich = box as RichTextBox;
            if (rich != null) rich.BorderStyle = BorderStyle.FixedSingle;
            if (!look.Hooked) box.ReadOnlyChanged += (s, e) => StyleOne((Control)s, Current, false);
            // a read-only single-line field keeps a slightly different back colour, as Windows shows it
            box.BackColor = box.ReadOnly && !box.Multiline ? p.WindowBack : p.FieldBack;
            box.ForeColor = p.TextColor;
            if (rich != null && darknessChanged && rich.TextLength > 0)
            {
                // coloured log lines written for the other kind of theme would be unreadable now
                int start = rich.SelectionStart, length = rich.SelectionLength;
                rich.SelectAll();
                rich.SelectionColor = p.TextColor;
                rich.Select(start, length);
            }
            Scrollbars(box, p);
        }

        // ---------------- group boxes, tabs, status bar ----------------

        private static readonly Regex SourceWord = new Regex(@"(^|[^a-z])(source|src)([^a-z]|$)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
        private static readonly Regex TargetWord = new Regex(@"(^|[^a-z])(target|trg|tgt)([^a-z]|$)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        /// <summary>1 when the words name the Source, 2 for the Target, 0 for neither or both.</summary>
        internal static int SideOf(string words)
        {
            words = words ?? string.Empty;
            bool source = SourceWord.IsMatch(words), target = TargetWord.IsMatch(words);
            return source == target ? 0 : source ? SideSource : SideTarget;
        }

        private static int SideOf(GroupBox group)
        {
            int named = SideOf(group.Text);
            if (named != 0) return named;
            Look look;
            return looks.TryGetValue(group, out look) ? look.Side : 0;
        }

        /// <summary>
        /// A group box as a card: the theme's border, a bold caption, and for a Source or Target group
        /// a tinted caption band with a line in that side's colour.
        /// </summary>
        private static void PaintGroup(object sender, PaintEventArgs e)
        {
            var group = (GroupBox)sender;
            UiPalette p = Current;
            Rectangle all = group.ClientRectangle;
            if (all.Width < 4 || all.Height < 4) return;
            int band = Math.Min(group.Font.Height + 3, all.Height - 2);
            int side = SideOf(group);
            using (var back = new SolidBrush(p.CardBack)) e.Graphics.FillRectangle(back, all);
            if (side != 0)
            {
                using (var tint = new SolidBrush(side == SideSource ? p.SourceTint : p.TargetTint))
                using (var line = new SolidBrush(side == SideSource ? p.Source : p.Target))
                {
                    e.Graphics.FillRectangle(tint, 1, 1, all.Width - 2, band);
                    e.Graphics.FillRectangle(line, 1, band, all.Width - 2, 2);
                }
            }
            using (var border = new Pen(p.Border)) e.Graphics.DrawRectangle(border, 0, 0, all.Width - 1, all.Height - 1);
            if (group.Text.Length == 0) return;
            Color back2 = side == SideSource ? p.SourceTint : side == SideTarget ? p.TargetTint : p.CardBack;
            using (var bold = new Font(group.Font, FontStyle.Bold))
            {
                TextRenderer.DrawText(e.Graphics, group.Text, bold, new Rectangle(8, 1, all.Width - 16, band),
                    group.Enabled ? p.TextColor : p.DisabledText, back2,
                    TextFormatFlags.Left | TextFormatFlags.VerticalCenter | TextFormatFlags.EndEllipsis | TextFormatFlags.SingleLine);
            }
        }

        private static void DrawTab(object sender, DrawItemEventArgs e)
        {
            var tabs = (TabControl)sender;
            if (e.Index < 0 || e.Index >= tabs.TabPages.Count) return;
            UiPalette p = Current;
            bool selected = e.Index == tabs.SelectedIndex;
            Rectangle area = e.Bounds;
            Color back = selected ? p.CardBack : p.WindowBack;
            using (var fill = new SolidBrush(back)) e.Graphics.FillRectangle(fill, area);
            if (selected)
                using (var line = new SolidBrush(p.Accent)) e.Graphics.FillRectangle(line, area.X, area.Y, area.Width, 3);
            TextRenderer.DrawText(e.Graphics, tabs.TabPages[e.Index].Text, tabs.Font, area,
                selected ? p.TextColor : p.MutedText, back,
                TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.EndEllipsis | TextFormatFlags.SingleLine);
        }

        private static void PaintStatusLine(object sender, PaintEventArgs e)
        {
            var bar = (Control)sender;
            using (var line = new Pen(Current.Border)) e.Graphics.DrawLine(line, 0, 0, bar.Width, 0);
        }

        // ---------------- grids ----------------

        private static void StyleGrid(DataGridView grid, Look look, UiPalette p)
        {
            grid.EnableHeadersVisualStyles = false;
            grid.BackgroundColor = p.CardBack;
            grid.GridColor = p.Border;
            grid.BorderStyle = BorderStyle.FixedSingle;
            grid.ColumnHeadersDefaultCellStyle.BackColor = p.Head;
            grid.ColumnHeadersDefaultCellStyle.ForeColor = p.HeadText;
            grid.ColumnHeadersDefaultCellStyle.SelectionBackColor = p.Head;
            grid.ColumnHeadersDefaultCellStyle.SelectionForeColor = p.HeadText;
            grid.RowHeadersDefaultCellStyle.BackColor = p.WindowBack;
            grid.RowHeadersDefaultCellStyle.ForeColor = p.TextColor;
            grid.RowHeadersDefaultCellStyle.SelectionBackColor = p.Accent;
            grid.RowHeadersDefaultCellStyle.SelectionForeColor = p.AccentText;
            grid.DefaultCellStyle.BackColor = p.CardBack;
            grid.DefaultCellStyle.ForeColor = p.TextColor;
            grid.DefaultCellStyle.SelectionBackColor = p.Accent;
            grid.DefaultCellStyle.SelectionForeColor = p.AccentText;
            foreach (DataGridViewColumn column in grid.Columns) TintColumn(column, p);
            if (!look.Hooked)
            {
                grid.ColumnAdded += (s, e) => TintColumn(e.Column, Current);
                grid.CellFormatting += KeepHighlightReadable;
            }
            foreach (Control bar in grid.Controls) if (bar is ScrollBar) Scrollbars(bar, p);
        }

        /// <summary>A column named after the Source or the Target is tinted in that side's colour.</summary>
        private static void TintColumn(DataGridViewColumn column, UiPalette p)
        {
            int side = SideOf(column.HeaderText);
            if (side == 0) side = SideOf(column.Name);
            column.DefaultCellStyle.BackColor = side == SideSource ? p.SourceTint : side == SideTarget ? p.TargetTint : Color.Empty;
        }

        /// <summary>Cells marked yellow as different keep black text in every theme.</summary>
        private static void KeepHighlightReadable(object sender, DataGridViewCellFormattingEventArgs e)
        {
            if (e.CellStyle.BackColor.ToArgb() != Color.Yellow.ToArgb()) return;
            e.CellStyle.ForeColor = Color.Black;
            e.CellStyle.SelectionForeColor = Current.AccentText;
        }

