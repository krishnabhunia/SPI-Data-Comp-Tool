        // ---------------- the parts Windows draws itself ----------------

        [DllImport("dwmapi.dll")]
        private static extern int DwmSetWindowAttribute(IntPtr window, int attribute, ref int value, int size);

        [DllImport("uxtheme.dll", CharSet = CharSet.Unicode)]
        private static extern int SetWindowTheme(IntPtr window, string app, string idList);

        private static bool OnWindows { get { return Environment.OSVersion.Platform == PlatformID.Win32NT; } }

        /// <summary>A dark title bar for the dark theme (Windows 10 1809 and later; older Windows keeps its own).</summary>
        private static void Chrome(Form form)
        {
            Look look = Of(form);
            bool dark = Current.Dark;
            // a light theme asks Windows for nothing unless the title bar was made dark earlier
            if (!OnWindows || !form.IsHandleCreated || dark == look.DarkParts) return;
            try
            {
                int value = dark ? 1 : 0;
                if (DwmSetWindowAttribute(form.Handle, 20, ref value, sizeof(int)) != 0)
                    DwmSetWindowAttribute(form.Handle, 19, ref value, sizeof(int));
                look.DarkParts = dark;
            }
            catch (Exception)
            {
                // the title bar stays as Windows draws it
            }
        }

        /// <summary>Dark scroll bars for the dark theme, where Windows offers them.</summary>
        private static void Scrollbars(Control c, UiPalette p)
        {
            if (!OnWindows) return;
            Look look = Of(c);
            if (!look.ScrollHooked)
            {
                look.ScrollHooked = true;
                // a new window handle starts with Windows' own look again
                c.HandleCreated += (s, e) => { Of((Control)s).DarkParts = false; Scrollbars((Control)s, Current); };
            }
            if (!c.IsHandleCreated || p.Dark == look.DarkParts) return;
            try
            {
                SetWindowTheme(c.Handle, p.Dark ? "DarkMode_Explorer" : null, null);
                look.DarkParts = p.Dark;
            }
            catch (Exception)
            {
                // the scroll bars stay as Windows draws them
            }
        }

        /// <summary>
        /// A progress bar in the theme's accent colour. Windows' themed bar ignores colours (it is
        /// always green), so the bar is switched to the plain drawing, which uses ForeColor on
        /// BackColor. That is done after the bar's window exists and outside its creation, and the
        /// bar's style is left alone, so its window is never rebuilt.
        /// </summary>
        private static void StyleProgress(ProgressBar bar, Look look, UiPalette p)
        {
            bar.ForeColor = p.Accent;
            bar.BackColor = p.Border;
            if (!OnWindows) return;
            if (!look.ScrollHooked)
            {
                look.ScrollHooked = true;
                bar.HandleCreated += (s, e) => { Of((Control)s).DarkParts = false; PlainBarLater((ProgressBar)s); };
            }
            if (bar.IsHandleCreated) PlainBarLater(bar);
        }

        private static void PlainBarLater(ProgressBar bar)
        {
            if (Of(bar).DarkParts) return;   // this window of the bar is plain already
            try { bar.BeginInvoke((MethodInvoker)(() => PlainBar(bar))); }
            catch (Exception)
            {
                // the bar stays green
            }
        }

        private static void PlainBar(ProgressBar bar)
        {
            if (bar.IsDisposed || !bar.IsHandleCreated) return;
            Look look = Of(bar);
            if (look.DarkParts) return;
            try
            {
                SetWindowTheme(bar.Handle, string.Empty, string.Empty);
                look.DarkParts = true;
            }
            catch (Exception)
            {
                // the bar stays green
            }
        }
