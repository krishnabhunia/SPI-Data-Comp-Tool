        private static UiPalette current;

        /// <summary>The theme in use. Read from the saved choice the first time it is needed.</summary>
        public static UiPalette Current
        {
            get
            {
                if (current == null)
                {
                    current = Load();
                    ToolStripManager.Renderer = new MenuRenderer();
                }
                return current;
            }
        }

        /// <summary>Raised after the theme has changed and every open window has been recoloured.</summary>
        public static event EventHandler Changed;

        // The names older code uses; they follow the current theme.
        public static Color WindowBack { get { return Current.WindowBack; } }
        public static Color CardBack { get { return Current.CardBack; } }
        public static Color Border { get { return Current.Border; } }
        public static Color Accent { get { return Current.Accent; } }
        public static Color TextColor { get { return Current.TextColor; } }
        public static Color MutedText { get { return Current.MutedText; } }

        private static Color Hex(string rgb)
        {
            return Color.FromArgb(Convert.ToInt32(rgb.Substring(0, 2), 16), Convert.ToInt32(rgb.Substring(2, 2), 16),
                Convert.ToInt32(rgb.Substring(4, 2), 16));
        }

        public static UiPalette Find(string name)
        {
            foreach (UiPalette p in All)
                if (string.Equals(p.Name, (name ?? string.Empty).Trim(), StringComparison.OrdinalIgnoreCase)) return p;
            return null;
        }

        // ---------------- the saved choice ----------------

        /// <summary>Outside the app folder, so an update or a reinstall keeps the choice.</summary>
        internal static string StorePath
        {
            get
            {
                return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
                    "SPI Data Comparison Tool", "theme.txt");
            }
        }

        private static UiPalette Load()
        {
            // CI checks of a finished build always use the default and never read the user's file.
            return SelfTest.IsRunning ? All[0] : ReadChoice(StorePath);
        }

        /// <summary>The theme named in the file; the default when the file is missing, unreadable or names no theme.</summary>
        internal static UiPalette ReadChoice(string path)
        {
            try
            {
                var file = new FileInfo(path);
                if (file.Exists && file.Length <= 64) return Find(File.ReadAllText(file.FullName)) ?? All[0];
            }
            catch (Exception)
            {
                // an unreadable choice is not worth stopping the app for: use the default
            }
            return All[0];
        }

        internal static void SaveChoice(string path, UiPalette palette)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, palette.Name);
        }

        /// <summary>
        /// Switches the theme and recolours every open window. Returns an empty string, or the reason
        /// the choice could not be saved (the theme still applies until the app closes).
        /// </summary>
        public static string Use(UiPalette palette, bool save = true)
        {
            if (palette == null) throw new ArgumentNullException(nameof(palette));
            bool darknessChanged = current != null && current.Dark != palette.Dark;
            current = palette;
            ToolStripManager.Renderer = new MenuRenderer();
            foreach (Form form in themed.ToArray())
            {
                if (form.IsDisposed) continue;
                Paint(form, darknessChanged);
            }
            EventHandler changed = Changed;
            if (changed != null) changed(null, EventArgs.Empty);
            if (!save || SelfTest.IsRunning) return string.Empty;
            try
            {
                SaveChoice(StorePath, palette);
                return string.Empty;
            }
            catch (Exception ex)
            {
                return ex.Message;
            }
        }

        // ---------------- applying a theme ----------------

        /// <summary>What the theme remembers about one control.</summary>
        private sealed class Look
        {
            public bool Hooked;        // events attached once
            public bool Main;          // the window's main button
            public int Zone;           // 0 ordinary, 1 header band, 2 status bar
            public int Side;           // 0 none, 1 Source, 2 Target
            public bool HasTone;       // a label whose colour the window set itself (red for an error ...)
            public Color Tone;
            public bool Toning;
            public bool ScrollHooked;  // waits for the control's window to exist
            public bool DarkParts;     // Windows was asked to draw this control's own parts dark
            public bool HasComboStyle;
            public FlatStyle ComboStyle;
        }

        private const int ZoneHeader = 1, ZoneStatus = 2, SideSource = 1, SideTarget = 2;
        private static readonly ConditionalWeakTable<Control, Look> looks = new ConditionalWeakTable<Control, Look>();
        private static readonly List<Form> themed = new List<Form>();
        private static Icon appIcon;

        private static Look Of(Control control) { return looks.GetOrCreateValue(control); }

        /// <summary>The app icon from the exe, so every window shows the same icon.</summary>
        public static void SetIcon(Form form)
        {
            try
            {
                if (appIcon == null) appIcon = Icon.ExtractAssociatedIcon(Application.ExecutablePath);
                if (appIcon != null) form.Icon = appIcon;
            }
            catch (Exception)
            {
                // keep the form's own icon if the exe icon cannot be read
            }
        }

        /// <summary>The coloured band at the top of the main window: its labels use the band's text colour.</summary>
        public static void MarkHeader(Control band) { Of(band).Zone = ZoneHeader; }

        /// <summary>A status bar at the bottom of a window.</summary>
        public static void MarkStatus(Control bar) { Of(bar).Zone = ZoneStatus; }

        /// <summary>The Source or the Target half of a connection, whatever its caption says.</summary>
        public static void MarkSide(GroupBox group, bool source) { Of(group).Side = source ? SideSource : SideTarget; }

        public static void Apply(Form form, params Button[] mainButtons)
        {
            if (form == null) return;
            SetIcon(form);
            Look look = Of(form);
            if (!look.Hooked)
            {
                look.Hooked = true;
                themed.Add(form);
                form.Disposed += (s, e) => themed.Remove((Form)s);
                form.HandleCreated += (s, e) => { Of((Control)s).DarkParts = false; Chrome((Form)s); };   // a new window starts light
                form.ControlAdded += OnControlAdded;
            }
            if (mainButtons != null)
            {
                foreach (Button b in mainButtons)
                {
                    if (b == null) continue;
                    Look main = Of(b);
                    if (main.Main) continue;
                    main.Main = true;
                    b.Font = new Font(b.Font, FontStyle.Bold);
                    b.EnabledChanged += (s, e) => ColorMainButton((Button)s);
                }
            }
            Paint(form, false);
        }

        /// <summary>Themes a window that has not asked for it itself (every tool window gets the same look).</summary>
        public static void EnsureApplied(Form form)
        {
            if (form != null && !Of(form).Hooked) Apply(form);
        }

        private static void Paint(Form form, bool darknessChanged)
        {
            UiPalette p = Current;
            form.BackColor = p.WindowBack;
            form.ForeColor = p.TextColor;
            StyleAll(form.Controls, p, darknessChanged);
            Chrome(form);
            form.Invalidate(true);
        }

        private static void OnControlAdded(object sender, ControlEventArgs e)
        {
            // controls a window creates later get the same look
            StyleOne(e.Control, Current, false);
        }

        private static void StyleAll(Control.ControlCollection controls, UiPalette p, bool darknessChanged)
        {
            foreach (Control c in controls) StyleOne(c, p, darknessChanged);
        }

        private static int ZoneOf(Control c)
        {
            for (Control at = c; at != null; at = at.Parent)
            {
                Look look;
                if (looks.TryGetValue(at, out look) && look.Zone != 0) return look.Zone;
            }
            return 0;
        }

        private static void StyleOne(Control c, UiPalette p, bool darknessChanged)
        {
            Look look = Of(c);
            int zone = ZoneOf(c);
            bool recurse = true;

            if (c is TileButton || c is GlyphIcon)
            {
                if (zone == ZoneHeader) c.ForeColor = p.HeadText;
                c.Invalidate();
                recurse = false;
            }
            else if (c is Button)
            {
                StyleButton((Button)c, look, p);
                recurse = false;
            }
            else if (c is GroupBox)
            {
                c.BackColor = p.CardBack;
                c.ForeColor = p.TextColor;
                if (!look.Hooked)
                {
                    c.Paint += PaintGroup;
                    Buffer(c);
                }
            }
            else if (c is TabControl)
            {
                var tabs = (TabControl)c;
                tabs.DrawMode = TabDrawMode.OwnerDrawFixed;
                if (!look.Hooked) tabs.DrawItem += DrawTab;
            }
            else if (c is TabPage)
            {
                ((TabPage)c).UseVisualStyleBackColor = false;
                c.BackColor = p.CardBack;
                c.ForeColor = p.TextColor;
            }
            else if (c is DataGridView)
            {
                StyleGrid((DataGridView)c, look, p);
                recurse = false;
            }
            else if (c is TextBoxBase)
            {
                StyleText((TextBoxBase)c, look, p, darknessChanged);
                recurse = false;
            }
            else if (c is ComboBox)
            {
                var combo = (ComboBox)c;
                if (!look.HasComboStyle) { look.HasComboStyle = true; look.ComboStyle = combo.FlatStyle; }
                // Windows draws its own light drop-down; only the flat style follows a dark theme
                combo.FlatStyle = p.Dark ? FlatStyle.Flat : look.ComboStyle;
                combo.BackColor = p.FieldBack;
                combo.ForeColor = p.TextColor;
                recurse = false;
            }
            else if (c is ListBox)
            {
                var list = (ListBox)c;
                list.BorderStyle = BorderStyle.FixedSingle;
                list.IntegralHeight = false;
                Field(c, p);
                recurse = false;
            }
            else if (c is ListView || c is TreeView || c is NumericUpDown)
            {
                Field(c, p);
                recurse = false;
            }
            else if (c is ProgressBar)
            {
                StyleProgress((ProgressBar)c, look, p);
                recurse = false;
            }
            else if (c is ToolStrip)
            {
                c.BackColor = c is StatusStrip ? p.StatusBack : p.CardBack;
                c.ForeColor = c is StatusStrip ? p.StatusText : p.TextColor;
                recurse = false;
            }
            else if (c is LinkLabel)
            {
                var link = (LinkLabel)c;
                link.LinkColor = zone == ZoneHeader ? p.HeadText : p.Info;
                link.ActiveLinkColor = zone == ZoneHeader ? p.HeadText : p.Accent;
                link.VisitedLinkColor = link.LinkColor;
            }
            else if (c is Label)
            {
                StyleLabel((Label)c, look, p, zone);
            }
            else if (c is CheckBox)
            {
                ((CheckBox)c).UseVisualStyleBackColor = true;
            }
            else if (c is TableLayoutPanel || c is FlowLayoutPanel)
            {
                c.BackColor = Color.Transparent;
            }

            if (look.Zone == ZoneHeader)
            {
                c.BackColor = p.Head;
                c.ForeColor = p.HeadText;
            }
            else if (look.Zone == ZoneStatus)
            {
                c.BackColor = p.StatusBack;
                c.ForeColor = p.StatusText;
                if (!look.Hooked) c.Paint += PaintStatusLine;
            }

            if (c.ContextMenuStrip != null)
            {
                c.ContextMenuStrip.BackColor = p.CardBack;
                c.ContextMenuStrip.ForeColor = p.TextColor;
            }
            if (!look.Hooked)
            {
                look.Hooked = true;
                if (recurse) c.ControlAdded += OnControlAdded;
            }
            if (recurse && c.HasChildren) StyleAll(c.Controls, p, darknessChanged);
        }

        /// <summary>The card is painted over the group box Windows draws; buffering shows only the finished picture.</summary>
        private static void Buffer(Control c)
        {
            try
            {
                System.Reflection.PropertyInfo buffered = typeof(Control).GetProperty("DoubleBuffered",
                    System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic);
                if (buffered != null) buffered.SetValue(c, true, null);
            }
            catch (Exception)
            {
                // without buffering the group box is still drawn correctly
            }
        }

        private static void Field(Control c, UiPalette p)
        {
            c.BackColor = p.FieldBack;
            c.ForeColor = p.TextColor;
            Scrollbars(c, p);
        }

        // ---------------- buttons ----------------

        private static void StyleButton(Button b, Look look, UiPalette p)
        {
            b.FlatStyle = FlatStyle.Flat;
            b.UseVisualStyleBackColor = false;
            b.Cursor = Cursors.Hand;
            if (!look.Hooked) b.Paint += PaintDisabled;
            if (look.Main)
            {
                b.FlatAppearance.MouseOverBackColor = p.AccentHover;
                b.FlatAppearance.MouseDownBackColor = p.AccentPressed;
                ColorMainButton(b);
                return;
            }
            b.BackColor = p.CardBack;
            b.ForeColor = p.TextColor;
            b.FlatAppearance.BorderColor = p.FieldBorder;
            b.FlatAppearance.MouseOverBackColor = p.HoverBack;
            b.FlatAppearance.MouseDownBackColor = p.PressedBack;
        }

        /// <summary>Main button: the theme's accent while it can be clicked; the plain disabled look otherwise.</summary>
        private static void ColorMainButton(Button b)
        {
            UiPalette p = Current;
            b.BackColor = b.Enabled ? p.Accent : p.DisabledBack;
            b.ForeColor = b.Enabled ? p.AccentText : p.DisabledText;
            b.FlatAppearance.BorderColor = b.Enabled ? p.Accent : p.Border;
        }

        /// <summary>Draws a disabled button with readable text instead of Windows' light-grey text.</summary>
        private static void PaintDisabled(object sender, PaintEventArgs e)
        {
            var b = (Button)sender;
            if (b.Enabled) return;
            UiPalette p = Current;
            var area = b.ClientRectangle;
            using (var back = new SolidBrush(p.DisabledBack))
            using (var border = new Pen(p.Border))
            {
                e.Graphics.FillRectangle(back, area);
                e.Graphics.DrawRectangle(border, area.X, area.Y, area.Width - 1, area.Height - 1);
            }
            TextRenderer.DrawText(e.Graphics, b.Text, b.Font, area, p.DisabledText, p.DisabledBack,
                TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.WordBreak |
                TextFormatFlags.EndEllipsis);
        }

