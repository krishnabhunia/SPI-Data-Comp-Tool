    /// <summary>The colours of one theme. Every text / background pair is checked by tests/test_ui_contrast.py.</summary>
    internal sealed class UiPalette
    {
        public string Name;      // saved in the theme file
        public string Title;     // shown in Settings
        public bool Dark;
        public Color WindowBack, CardBack, TextColor, MutedText, Border;
        public Color Head, HeadText;                                  // header band, grid headers
        public Color Accent, AccentText, AccentHover, AccentPressed;  // the main button
        public Color Source, SourceTint, Target, TargetTint;          // Source and Target are told apart by colour
        public Color Tile1, Tile2, Tile3, Tile4;                      // the four tool tiles of the main window
        public Color StatusBack, StatusText;
        public Color FieldBack, FieldBorder;
        public Color DisabledBack, DisabledText;
        public Color HoverBack, PressedBack;                          // ordinary buttons, menu items
        public Color Danger, Success, Info;                           // status text

        public Color Tile(int index)
        {
            switch (((index % 4) + 4) % 4)
            {
                case 0: return Tile1;
                case 1: return Tile2;
                case 2: return Tile3;
                default: return Tile4;
            }
        }

        public override string ToString() { return Title; }
    }

